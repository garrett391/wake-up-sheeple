ROOT = pathlib.Path(__file__).resolve().parent.parent
URL = (ROOT / "test/index.html").as_uri() + "?debug=1"
SH = ROOT / "shots"
errors = []

def ev(page, js):
    return page.evaluate(js)

def dlg_close(page, n=6):
    for _ in range(n):
        if ev(page, "__wus.state().modal") != "dialog":
            return
        labels = ev(page, "__wus.choices()")
        idx = next((i for i, l in enumerate(labels) if l.endswith("Leave")), 0 if len(labels) == 1 else len(labels) - 1)
        ev(page, f"__wus.choose({idx})"); page.wait_for_timeout(120)

